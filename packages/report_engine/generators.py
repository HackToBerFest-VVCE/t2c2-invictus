"""Report generators for Markdown, JSON, and GitHub Issue drafts."""

import json
from dataclasses import asdict
from .models import VerificationReport
from packages.verifier.models import VerificationStatus


class MarkdownReportGenerator:
    """Renders structured GitHub-Flavored Markdown verification reports."""

    def generate(self, report: VerificationReport) -> str:
        status_badge = {
            VerificationStatus.VERIFIED_PASS: "PASSED (VERIFIED)",
            VerificationStatus.VERIFIED_FAILURE: "FAILED (VERIFIED)",
            VerificationStatus.CHECK_ERROR: "ERROR (CHECK INCONCLUSIVE)",
            VerificationStatus.UNSUPPORTED: "UNSUPPORTED",
            VerificationStatus.STATIC_WARNING: "WARNING",
            VerificationStatus.AI_HYPOTHESIS: "ADVISORY HYPOTHESIS",
        }.get(report.status, report.status.value)

        lines = [
            f"# Invariant Verification Report: `{report.run_id}`",
            "",
            f"**Overall Status**: `{status_badge}`",
            f"**Duration**: {report.duration_ms} ms | **Invariants Tracked**: {report.invariants_evaluated}",
            f"**Passed Tests**: {report.passed_count} | **Failed Tests**: {report.failed_count} | **AI Hypotheses**: {report.hypothesis_count}",
            "",
            f"> {report.summary}",
            "",
            "---",
            "",
            "## Findings Summary",
            "",
        ]

        if not report.findings:
            lines.append("No issues or invariant violations detected. All checks passed.")
            return "\n".join(lines)

        lines.extend([
            "| ID | Title | Invariant | Severity | Status | Origin |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])

        for f in report.findings:
            origin = "AI Hypothesis" if f.ai_assisted else "Runner Evidence"
            inv_ref = f.invariant_id or "N/A"
            lines.append(
                f"| `{f.finding_id}` | {f.title} | `{inv_ref}` | **{f.severity}** | `{f.status.value}` | {origin} |"
            )

        lines.append("")
        lines.append("## Detailed Findings & Reproduction Evidence")
        lines.append("")

        for f in report.findings:
            lines.extend([
                f"### Finding: {f.title} (`{f.finding_id}`)",
                f"* **Status**: `{f.status.value}`",
                f"* **Severity**: {f.severity}",
                f"* **Associated Invariant**: {f.invariant_id or 'None'}",
            ])
            if f.reproduction_command:
                lines.append(f"* **Reproduction / Test Input**: `{f.reproduction_command}`")
            if f.execution_trace:
                lines.extend([
                    "* **Evidence Trace**:",
                    "```",
                    f.execution_trace.strip(),
                    "```",
                ])
            lines.append("")

        return "\n".join(lines)


class JSONReportGenerator:
    """Renders structured JSON report for machine consumption."""

    def generate(self, report: VerificationReport) -> str:
        report_dict = asdict(report)
        # Convert enums to string
        report_dict["status"] = report.status.value
        for f in report_dict["findings"]:
            f["status"] = f["status"].value if hasattr(f["status"], "value") else str(f["status"])
        return json.dumps(report_dict, indent=2)


class GitHubIssueDraftGenerator:
    """Generates pre-filled GitHub Issue drafts for verified failures."""

    def generate(self, report: VerificationReport) -> str:
        failures = [
            f for f in report.findings if f.status == VerificationStatus.VERIFIED_FAILURE
        ]
        if not failures:
            return ""

        f = failures[0]
        return f"""Title: [BUG] Verified Invariant Violation: {f.title}

### Verified Invariant Violation
* **Finding ID**: `{f.finding_id}`
* **Invariant Clause**: `{f.invariant_id or 'General State Invariant'}`
* **Severity**: {f.severity}
* **Reproduction Command**:
```bash
{f.reproduction_command or 'pytest'}
```

### Execution Trace & Evidence
```
{f.execution_trace or 'Assertion failed.'}
```

*Automated report generated by Invariant Continuous Verification Platform.*
"""
